import type { BigIntStats } from "node:fs";

/** Pure comparison of already collected stat facts; no resource authority. */
export function sameHostedDependencyStatFacts(a: BigIntStats, b: BigIntStats): boolean {
  return a.dev === b.dev && a.ino === b.ino && a.mode === b.mode && a.uid === b.uid && a.gid === b.gid &&
    a.nlink === b.nlink && a.size === b.size && a.mtimeNs === b.mtimeNs && a.ctimeNs === b.ctimeNs;
}
