import { ChildLifetime } from "@vioxen/subscription-runtime/core";
import { fileURLToPath } from "node:url";
import type { AgentRuntimeToolName } from "@vioxen/subscription-runtime/core";
import {
  CodexModelBackend,
  codexMimoApiKeyEnvVarDefault,
  codexMimoTokenPlanEgressPolicy,
  codexModelBackendExcludesConfigKey,
  codexModelBackendModelProvidersConfigToml,
  codexProviderEgressConfigToml,
  hostedCodexPermissionProfilesToml,
  type CodexProviderEgressPolicy,
} from "@vioxen/subscription-runtime/provider-codex";
import { normalizeBoundedWorkspaceTools } from "./bounded-workspace-tool-policy";

const mcpServerName = "agent_runtime_workspace";

export type CodexWorkspaceToolsProfile = {
  readonly configToml: string;
  readonly developerInstructions: string;
};

export function buildCodexWorkspaceToolsProfile(input: {
  readonly childLifetime?: ChildLifetime;
  readonly workspaceRoot: string;
  readonly allowedTools: readonly AgentRuntimeToolName[];
  readonly denyProjectInstructions?: boolean;
  readonly nativeGoalControls?: true;
  readonly hostedEgressPolicy?: CodexProviderEgressPolicy;
  /** Defaults to {@link CodexModelBackend.OpenAiChatGpt} — omitting it keeps today's generated config.toml byte-identical. */
  readonly modelBackend?: CodexModelBackend;
  /** Env var holding the MiMo Token Plan key. Only used when `modelBackend` is `XiaomiMimoTokenPlan`. */
  readonly mimoApiKeyEnvVarName?: string;
}): CodexWorkspaceToolsProfile {
  const cliPath = fileURLToPath(
    new URL("../workspace-tools-mcp.js", import.meta.url),
  );
  const enabledTools = normalizeBoundedWorkspaceTools(input.allowedTools);
  const modelBackend = input.modelBackend ?? CodexModelBackend.OpenAiChatGpt;
  const args = [
    cliPath,
    "--workspace-root",
    input.workspaceRoot,
    "--allow",
    enabledTools.join(","),
    ...(input.denyProjectInstructions ? ["--deny-project-instructions"] : []),
    ...(input.childLifetime ? ["--child-lifetime-json", JSON.stringify(input.childLifetime)] : []),
  ];
  const configToml = [
    "# Generated by Agent Runtime. Native Codex tools stay disabled.",
    'cli_auth_credentials_store = "file"',
    'approval_policy = "never"',
    ...(input.hostedEgressPolicy
      ? ['default_permissions = "hosted-project-read"']
      : ['sandbox_mode = "read-only"']),
    'web_search = "disabled"',
    "disable_response_storage = true",
    ...(codexModelBackendExcludesConfigKey(modelBackend, "model_verbosity")
      ? []
      : ['model_verbosity = "low"']),
    ...(input.denyProjectInstructions ? ["project_doc_max_bytes = 0"] : []),
    "",
    "[features]",
    "apps = false",
    "hooks = false",
    "memories = false",
    "multi_agent = false",
    "shell_snapshot = false",
    "shell_tool = false",
    "skill_mcp_dependency_install = false",
    "unified_exec = false",
    "",
    "[tools]",
    "view_image = false",
    "",
    `[projects.${quoteTomlKey(input.workspaceRoot)}]`,
    'trust_level = "untrusted"',
    "",
    "[history]",
    'persistence = "none"',
    "",
    "[otel]",
    'exporter = "none"',
    'metrics_exporter = "none"',
    'trace_exporter = "none"',
    "log_user_prompt = false",
    "",
    `[mcp_servers.${mcpServerName}]`,
    `command = ${tomlString(process.execPath)}`,
    `args = ${tomlStringArray(args)}`,
    `cwd = ${tomlString(input.workspaceRoot)}`,
    ...((input.childLifetime || modelBackend === CodexModelBackend.XiaomiMimoTokenPlan)
      ? ['env_vars = ["PATH", "HOME", "CI", "CODEX_HOME"]'] : []),
    `enabled_tools = ${tomlStringArray(enabledTools)}`,
    'default_tools_approval_mode = "approve"',
    "",
    "[shell_environment_policy]",
    'inherit = "none"',
    'include_only = ["PATH", "HOME", "CI", "CODEX_HOME"]',
    "",
    ...(modelBackend === CodexModelBackend.OpenAiChatGpt ? [] : [
      codexModelBackendModelProvidersConfigToml({
        backend: modelBackend,
        envKeyName: input.mimoApiKeyEnvVarName ?? codexMimoApiKeyEnvVarDefault,
      }),
    ]),
    ...(input.hostedEgressPolicy
      ? [codexProviderEgressConfigToml(input.hostedEgressPolicy, { namedPermissions: true }),
          hostedCodexPermissionProfilesToml(input.hostedEgressPolicy)]
      : modelBackend === CodexModelBackend.XiaomiMimoTokenPlan
        ? [codexProviderEgressConfigToml(codexMimoTokenPlanEgressPolicy())]
        : []),
  ].join("\n");
  return {
    configToml: `${configToml}\n`,
    developerInstructions: [
      input.nativeGoalControls
        ? 'Use only the agent_runtime_workspace MCP tools for filesystem operations. An active Goal is already provided: use get_goal to inspect it and do not create another Goal. Work autonomously without requesting human input. After independently verifying that the objective is satisfied, call update_goal({status:"complete"}) before your final response.'
        : "Use only the agent_runtime_workspace MCP tools exposed for this task.",
      "Native shell, web, delegation, applications, and direct environment tools are unavailable.",
      "All paths must be relative to the provided workspace root.",
    ].join(" "),
  };
}

function tomlString(value: string): string {
  return JSON.stringify(value);
}

function tomlStringArray(values: readonly string[]): string {
  return `[${values.map(tomlString).join(", ")}]`;
}

function quoteTomlKey(value: string): string {
  return JSON.stringify(value);
}
