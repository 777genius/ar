import { parseMimoProjectBridgeRequest } from "../worker-codex/hosted-mimo-project-bridge-contract.js";
/** A separate finite wire kind. Never normalize malformed reserved NativeProbe
 * bytes into an outer job or discard duplicate/escaped kind spellings. */
export function readMimoProjectIngress(original: Buffer): Record<string, unknown> | null {
  if (original.length > 65536) throw new Error("request too large");
  const bytes = new TextDecoder("utf-8", { fatal: true }).decode(original);
  const value: unknown = JSON.parse(bytes);
  if (!value || typeof value !== "object" || Array.isArray(value) || !("kind" in value) || value.kind !== "MimoProject") return null;
  // New MiMo requests use compact JSON generated by the fixed transport.
  // This equality rejects duplicates and escaped keys before JSON.parse's
  // normalized object can erase reserved original-wire evidence.
  if (JSON.stringify(value) !== bytes) throw new Error("mimo_project_bridge_request_invalid");
  return parseMimoProjectBridgeRequest(value) as unknown as Record<string, unknown>;
}
